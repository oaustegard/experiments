#!/usr/bin/env python3
"""Copy the numbers RESULTS.md cites into results/summary.json, converted to the units the prose uses
(F1 in points, sizes in MB of 10^6 bytes, seconds in minutes or hours). Every value is read from a result
file here; nothing is typed by hand.

  python3 gliner-browser/run/summarize.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
R = HERE / "results"


def load(name):
    return json.loads((R / name).read_text())


def pts(x):
    return round(100 * x, 4)


def mb(n):
    return round(n / 1e6, 4)


out = {"note": "generated by run/summarize.py from the files named in each section; F1 in points, sizes in MB (10^6 bytes)"}

# Baselines and round 1 arms (bench.test_mean7 at threshold 0.5, the upstream default)
base = {"B1": "B1_gliner_small-v2.1", "B2": "B2_gliner_small-v2.5", "B3": "B3_gliner-bi-edge-v2.0",
        "B4": "B4_gliner_large-v2.1"}
out["baselines"] = {}
for k, f in base.items():
    d = load(f + ".json")
    b = d["bench"]
    out["baselines"][k] = {"model": d["model"], "params_M": round(d["params"] / 1e6, 2),
                           "test_at_05": pts(b["test_mean7"]["0.5"]), "test_at_04": pts(b["test_mean7"]["0.4"]),
                           "dev_best_threshold": b["dev_best_threshold"],
                           "test_at_dev_best": pts(b["test_mean7_at_dev_best"]), "bench_seconds": b["seconds"]}

out["arms"] = {}
train_s = 0.0
for a in ["A0", "A3", "A4", "A6"]:
    d = load(a + ".json")
    b = d["bench"]
    train_s += d["train_seconds"]
    out["arms"][a] = {"test_at_05": pts(b["test_mean7"]["0.5"]), "dev_best_threshold": b["dev_best_threshold"],
                      "dev_best": pts(b["dev_best_mean5"]), "test_at_dev_best": pts(b["test_mean7_at_dev_best"]),
                      "best_step": d["best_step"], "steps": d["args"]["steps"], "train_minutes": round(d["train_seconds"] / 60, 2),
                      "params_M": round(d["params"]["total"] / 1e6, 2), "prefix_space": d["args"]["prefix_space"]}
A = out["arms"]
B1 = out["baselines"]["B1"]["test_at_05"]
out["round1"] = {
    "leading_space_gain": round(A["A6"]["test_at_05"] - A["A4"]["test_at_05"], 4),
    "leading_space_gain_at_dev_best": round(A["A6"]["test_at_dev_best"] - A["A4"]["test_at_dev_best"], 4),
    "best_arm_gap_to_B1": round(B1 - A["A6"]["test_at_05"], 4),
    "lr_gain_A4_vs_A3": round(A["A4"]["test_at_05"] - A["A3"]["test_at_05"], 4),
    "train_hours_four_arms": round(train_s / 3600, 2),
}

# Packing cost on gliner-bi-edge-v2.0 (pack_cost_biedge.json, bench.summary, test mean of 7 at 0.5)
pc = load("pack_cost_biedge.json")
s = pc["bench"]["summary"]
out["pack_cost"] = {k: {"test_at_05": pts(v["test_mean7@0.5"]), "delta_test_at_05": round(100 * v["delta_test_mean7@0.5_vs_fp32"], 4),
                        "delta_dev_at_05": round(100 * v["delta_dev_mean5@0.5_vs_fp32"], 4),
                        "cost_test_at_05": round(-100 * v["delta_test_mean7@0.5_vs_fp32"], 4)} for k, v in s.items()}
chk = pc["bench"]["fp32_arm_check"]
out["pack_cost_fp32_check"] = {"cells": chk["cells"], "cells_differing": chk["cells_differing"]}
sz = pc["sizes"]


def enc(p):
    return {"text_encoder_brotli_MB": mb(p["text_token_table"]["brotli"] + p["text_layers"]["brotli"]),
            "label_encoder_brotli_MB": mb(p["label_token_table"]["brotli"] + p["label_layers"]["brotli"]),
            "span_head_brotli_MB": mb(p["span_head"]["brotli"]),
            "weights_raw_MB": mb(p["weights_total"]["raw"]), "download_raw_MB": mb(p["download_total"]["raw"]),
            "download_brotli_MB": mb(p["download_total"]["brotli"]), "brotli_quality": p["brotli_quality"]}


out["sizes"] = {"fp32": enc(sz["F"]), "shipped_pack_q11": enc(sz["Q"])}
web = json.loads((HERE / "web/models/gliner-bi-edge-v2.0-t4-w8L63-h8/sizes.json").read_text())
out["sizes"]["shipped_pack_files_q9"] = enc(web)
out["sizes"]["fp32_over_pack_raw"] = round(sz["F"]["download_total"]["raw"] / sz["Q"]["download_total"]["raw"], 2)
st = pc["stage_timing"]["Q_t4-w8L63+label_t4-w8L63+h8"]
out["numpy_cpu_timing"] = {"text_encoder_ms": round(st["text_encoder"]["mean_ms"], 3),
                           "label_encoder_ms_per_label": round(st["label_encoder_per_label"]["mean_ms"], 3),
                           "mean_text_tokens": round(st["mean_text_tokens"], 2)}

# Reference parity (pack_parity_biedge.json) and the round 1 packer on smoke checkpoints (pack_parity.json)
pb = load("pack_parity_biedge.json")["gliner-bi-edge-v2.0"]
a = pb["a_logits_fp32_vs_library"]
short = [x for x in pb["per_input"] if x["n_tokens"] <= 1024]
longest = max(pb["per_input"], key=lambda x: x["max_abs"])
out["reference_parity"] = {"inputs": a["n_inputs"], "max_abs_logit_diff": a["max_abs_logit_diff"],
                           "max_abs_logit_diff_tokens": longest["n_tokens"],
                           "max_abs_logit_diff_up_to_1024_tokens": max(x["max_abs"] for x in short),
                           "inputs_up_to_1024_tokens": len(short),
                           "entities_identical_at_05": pb["b_entities_vs_predict_entities"]["own_bias@0.5"]["inputs_identical"]}
split = pb["c_quantized_vs_fp32"]["t4-w8L63_error_split"]
out["reference_parity"]["quantized_logit_shift"] = {k: round(v["mean_abs_logit_diff"], 4) for k, v in split.items() if isinstance(v, dict)}
out["reference_parity"]["fp32_logit_std"] = round(split["fp32_logit_std"], 4)
out["smoke_packer_max_abs_logit_diff"] = load("pack_parity.json")["smoke_b"]["a_logits_fp32_vs_library"]["max_abs_logit_diff"]

# Browser vs NumPy reference, headless Chromium (web_parity.json)
wp = load("web_parity.json")
out["web_parity"] = {}
for k, p in wp["packs"].items():
    g = p["heads"]["gpu"]
    out["web_parity"][k] = {"cases": g["nCases"], "logit_max_abs_diff": g["logitMaxAbsDiff"],
                            "entity_checks": g["entityChecks"], "entity_matches": g["entityMatches"],
                            "gpu_vs_js_head_max_abs_diff": p["headsMaxAbsDiff"]}
out["web_parity_wall_minutes"] = round(wp["wallS"] / 60, 2)
out["headless_js_label_encoder_ms_per_label_50"] = round(wp["cpu"]["labels50_cold"]["labelEncoderMsPerLabel"], 3)

# Real GPU, Oskar's Mac (bridge_gliner-web-2.json)
br = load("bridge_gliner-web-2.json")
o = br["outputs"]
t = o["timing"]
g, j = t["gpu"], t["js"]
lc = t["labelEncoderCold"]
out["mac"] = {
    "gpu": o["describe"]["vendor"] + " " + o["describe"]["architecture"],
    "run_seconds": round(br["runMs"] / 1000, 2),
    "parity_logit_max_abs_diff": o["parity"]["heads"]["gpu"]["logitMaxAbsDiff"],
    "parity_entity_matches": o["parity"]["heads"]["gpu"]["entityMatches"],
    "parity_entity_checks": o["parity"]["heads"]["gpu"]["entityChecks"],
    "gpu_head_256tok_10lab_total_ms": round(g["text256_labels10"]["median"]["totalMs"], 3),
    "gpu_head_30tok_10lab_total_ms": round(g["text30_labels10"]["median"]["totalMs"], 3),
    "gpu_head_30tok_50lab_total_ms": round(g["text30_labels50"]["median"]["totalMs"], 3),
    "js_head_30tok_10lab_span_words_ms": round(j["text30_labels10"]["median"]["spanWordsMs"], 3),
    "js_head_30tok_10lab_span_head_ms": round(j["text30_labels10"]["median"]["spanHeadMs"], 3),
    "js_head_30tok_10lab_total_ms": round(j["text30_labels10"]["median"]["totalMs"], 3),
    "js_head_256tok_10lab_total_ms": round(j["text256_labels10"]["median"]["totalMs"], 3),
    "batch100_texts_per_second_pipelined": round(g["batch100_labels20_pipelined"]["textsPerSecond"], 1),
    "batch100_texts_per_second_serial": round(g["batch100_labels20_serial"]["textsPerSecond"], 1),
    "batch100_js_head_texts_per_second_serial": round(j["batch100_labels20_serial"]["textsPerSecond"], 2),
    "batch100_tokens": g["batch100_labels20_serial"]["tokens"],
    "label_encoder_ms_per_label_10": round(lc["labels10"]["msPerLabel"], 2),
    "label_encoder_ms_per_label_50": round(lc["labels50"]["msPerLabel"], 2),
    "label_set_10_cold_ms": round(lc["labels10"]["labelEncoderMs"] + lc["labels10"]["labelProjectionMs"], 2),
}
m = out["mac"]
m["js_over_gpu_30tok"] = round(m["js_head_30tok_10lab_total_ms"] / m["gpu_head_30tok_10lab_total_ms"], 1)

(R / "summary.json").write_text(json.dumps(out, indent=1) + "\n")
print(json.dumps(out, indent=1))
