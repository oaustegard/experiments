#!/usr/bin/env python3
"""(Re)build tests/suites/gcc-compile from gcc.c-torture/compile.

    git clone --depth 1 --filter=blob:none --sparse https://github.com/gcc-mirror/gcc.git tests/tools/src/gcc
    (cd tests/tools/src/gcc && git sparse-checkout set gcc/testsuite/gcc.c-torture/compile gcc/testsuite/gcc.dg)
    python3 tests/scripts/import_gcc_compile.py [tests/tools/src/gcc]

Copies every compile/*.c, turns the dg-options that matter (-std=, -fgnu89-inline, ...)
into <test>.c.flags, and writes skip.txt with a reason per skipped test: dg-error
tests (gcc must reject them), unsupported dg-require-effective-target, target-specific
options, other-target guards, and whatever gcc -O0 -w -S itself rejects on this host.
Pass (driver compileonly) = the compiler's -S succeeds and `as` accepts the output.
"""
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TESTS = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import dg  # noqa: E402

DEST = os.path.join(TESTS, "suites", "gcc-compile")


def classify(text):
    dirs = dg.directives(text)
    flags, opt_reasons = dg.options(dirs)
    flags = ["-std=gnu2x" if f == "-std=gnu23" else "-std=c2x" if f == "-std=c23" else f for f in flags]
    reason = None
    if any(n == "dg-error" for n, _ in dirs):
        reason = "dg-error: gcc must reject this test"
    reason = reason or dg.skip_if(dirs, flags) or (opt_reasons[0] if opt_reasons else None)
    return flags, reason


def main():
    src_root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(TESTS, "tools", "src", "gcc")
    comp = os.path.join(src_root, "gcc", "testsuite", "gcc.c-torture", "compile")
    os.makedirs(DEST, exist_ok=True)
    for f in os.listdir(DEST):
        if f.endswith((".c", ".h", ".flags")) or f == "skip.txt":
            os.remove(os.path.join(DEST, f))
    skips = {}
    names = sorted(f for f in os.listdir(comp) if f.endswith((".c", ".h")))
    for f in names:
        shutil.copy(os.path.join(comp, f), DEST)
    n = 0
    for f in names:
        if not f.endswith(".c"):
            continue
        n += 1
        text = open(os.path.join(DEST, f), errors="replace").read()
        flags, reason = classify(text)
        if flags:
            with open(os.path.join(DEST, f + ".flags"), "w") as fh:
                fh.write(" ".join(flags) + "\n")
        if reason:
            skips[f] = reason
    write_skips(skips)
    # Everything left must be accepted by gcc -O0 -w -S.
    out = os.path.join(DEST, ".gcc-baseline.json")
    subprocess.run([sys.executable, os.path.join(TESTS, "run.py"), "--suite", "gcc-compile",
                    "--cc", "gcc -O0", "--jobs", "2", "--json", out, "-q"], check=False)
    for tid, r in json.load(open(out)).items():
        if r["status"] != "PASS":
            skips[tid.split("/", 1)[1]] = "gcc -O0 -w rejects it (%s: %s)" % (r["stage"], r["reason"][:80])
    os.remove(out)
    write_skips(skips)
    rev = subprocess.run(["git", "-C", src_root, "log", "-1", "--format=%H"], capture_output=True, text=True).stdout.strip()
    with open(os.path.join(DEST, "SOURCE"), "w") as fh:
        fh.write("https://github.com/gcc-mirror/gcc %s gcc/testsuite/gcc.c-torture/compile\n" % rev)
    print("imported %d tests, %d skipped, %d active" % (n, len(skips), n - len(skips)))


def write_skips(skips):
    with open(os.path.join(DEST, "skip.txt"), "w") as fh:
        fh.write("# Generated by tests/scripts/import_gcc_compile.py: <test>  # reason\n")
        for f in sorted(skips):
            fh.write("%s  # %s\n" % (f, skips[f].replace("\n", " ")))


if __name__ == "__main__":
    main()
