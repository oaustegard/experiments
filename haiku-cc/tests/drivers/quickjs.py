"""Driver for the `quickjs` suite: QuickJS (release 2026-06-04) built by hcc.

Test ids:
  quickjs/js/<category>_<nn>_<slug>.js   our own small program (generated by
        tests/scripts/gen_quickjs_scripts.py, committed): language features, builtins,
        std/os modules, small algorithms, error exits.
  quickjs/js/upstream/test_*.js          the upstream tests/ files (assert-based, silent on success).
  quickjs/test262/<dir>/<name>.js  a test from tc39/test262 (selected and committed by
        tests/scripts/gen_test262.py; harness files in quickjs/test262-harness/).  The test is
        assembled the way test262 prescribes (assert.js, sta.js, includes, "use strict" for
        onlyStrict, doneprintHandle.js for async) and run as a script; the generator kept only
        tests whose outcome under the gcc-built qjs is the one test262 expects.
  quickjs/test262x/<dir>/<name>.js  test262 tests that need what plain qjs lacks ($262.createRealm /
        agent / evalScript / detachArrayBuffer, module code, ...), run with QuickJS's own runner
        `run-test262 -c <conf> -f <file>` built from run-test262.c by the compiler under test; exit
        code and output must equal the gcc-built run-test262's.
  quickjs/build/<f>.c                    hcc compiles that one file (cutils, dtoa, libregexp,
        libunicode, quickjs, quickjs-libc, qjs, repl).  repl.c is generated by a gcc-built qjsc.
  quickjs/build/version                  the hcc-built qjs starts and evaluates 1+1.
Each js test runs `qjs [--std] <file>` in a private copy of the js/ tree (TZ=UTC); the exit
code, stdout and stderr must equal those of a gcc -O0 build.  All eight C files of the
hcc-built qjs are compiled once per hcc revision and cached (tests/drivers/common.py).
The release tarball (~600 KB) is downloaded into tests/tools/quickjs on first use (sha256 pinned).
"""
import glob
import os
import re
import shutil
import subprocess
import tarfile

import common as C

NAME = "quickjs-2026-06-04"
URL = "https://bellard.org/quickjs/quickjs-2026-06-04.tar.xz"
SHA256 = "b376e839b322978313d929fd20663b11ba58b75df5a46c126dd19ea2fa70ad2a"
LIB = ["cutils", "dtoa", "libregexp", "libunicode", "quickjs", "quickjs-libc"]
ALL = LIB + ["qjs", "repl"]
RT = LIB + ["run-test262"]  # objects of the run-test262 program (QuickJS's own test262 runner: $262, agents, modules)
LDFLAGS = ["-lm", "-lpthread", "-ldl"]
RUN_TIMEOUT = 300
STD_FLAG = {"test_builtin.js", "test_std.js"}
UPSTREAM_SKIP = {"assert.js", "fixture_cyclic_import.js", "test_worker_module.js"}


def list_tests(suite):
    js = os.path.join(suite.dir, "js")
    out = ["js/" + os.path.basename(p) for p in glob.glob(os.path.join(js, "*.js")) if not os.path.basename(p).startswith("_")]
    out += ["js/upstream/" + os.path.basename(p) for p in glob.glob(os.path.join(js, "upstream", "test_*.js"))
            if os.path.basename(p) not in UPSTREAM_SKIP]
    for sub in ("test262", "test262x"):
        for dp, dn, fn in os.walk(os.path.join(suite.dir, sub)):
            dn.sort()
            out += [os.path.relpath(os.path.join(dp, f), suite.dir) for f in fn if f.endswith(".js") and "_FIXTURE" not in f]
    return out + ["build/%s.c" % f for f in ALL + ["run-test262"]] + ["build/version"]


def source_dir():
    root = os.path.join(C.tools_root(), "quickjs")
    d = os.path.join(root, NAME)
    if os.path.exists(os.path.join(d, "quickjs.c")):
        return d
    tpath = C.fetch(URL, os.path.join(root, "dl", os.path.basename(URL)), SHA256)
    with C.locked(d):
        if not os.path.exists(os.path.join(d, "quickjs.c")):
            with tarfile.open(tpath) as t:
                t.extractall(root)
    return d


def flags(suite, cc_argv):
    return suite.cflags(cc_argv)


def gflags(suite):
    return list(suite.cfg["cflags"])


def src_hash(d):
    return C.sha(*[C.file_sha(p) for p in sorted(glob.glob(os.path.join(d, "*.[ch]")))] + [C.file_sha(os.path.join(d, "repl.js"))])


def repl_c(R, suite):
    """repl.c, generated once by a gcc-built qjsc (it is bytecode for repl.js)."""
    d = source_dir()

    def build(out):
        work = os.path.dirname(out)
        objs = []
        fl = gflags(suite) + ['-DCONFIG_CC="gcc"', '-DCONFIG_PREFIX="/usr/local"']
        for f in LIB + ["qjsc"]:
            objs.append(C.gcc_object(fl, os.path.join(d, f + ".c"), "quickjs/qjsc-" + f))
        qjsc = os.path.join(work, "qjsc")
        fail = C.link(R, qjsc, objs, LDFLAGS, work)
        if fail:
            return fail
        r = subprocess.run([qjsc, "-s", "-c", "-o", out, "-m", os.path.join(d, "repl.js")], capture_output=True, text=True, cwd=work)
        if r.returncode != 0:
            return C.Failure("FAIL", "link", "qjsc failed: " + r.stderr[-200:])
        return None
    path, fail = C.cached_program(R, "qjs-repl-c", [C.gcc_fingerprint(), src_hash(d), " ".join(gflags(suite))], build)
    if fail:
        raise RuntimeError("generating repl.c failed: " + fail.reason)
    return path


def source_for(R, suite, f):
    if f == "repl":
        return repl_c(R, suite)
    return os.path.join(source_dir(), f + ".c")


def ref_qjs(R, suite):
    d = source_dir()
    objs = [C.gcc_object(gflags(suite), source_for(R, suite, f) if f == "repl" else os.path.join(d, f + ".c"), "quickjs/" + f)
            for f in ALL]

    def build(out):
        return C.link(R, out, objs, LDFLAGS, os.path.dirname(out))
    path, fail = C.cached_program(R, "qjs-ref", [C.gcc_fingerprint(), src_hash(d), " ".join(gflags(suite))], build)
    if fail:
        raise RuntimeError("reference qjs failed to link: " + fail.reason)
    return path


def hcc_object(R, suite, cc_argv, f):
    src = source_for(R, suite, f)
    if f == "repl":  # cached_object keys on content; cache path has no .c suffix, so copy
        cp = os.path.join(os.path.dirname(src), "repl.c")
        if not os.path.exists(cp):
            shutil.copy(src, cp)
        src = cp
    return C.cached_object(R, cc_argv, flags(suite, cc_argv), src, "quickjs/" + f, 3600)


def hcc_qjs(R, suite, cc_argv):
    d = source_dir()

    def build(out):
        objs, first = [], None
        for f in ALL:
            obj, fail = hcc_object(R, suite, cc_argv, f)
            if fail:
                first = first or C.Failure(fail.status, fail.stage, "quickjs build: %s.c: %s" % (f, fail.reason), fail.log)
            else:
                objs.append(obj)
        if first:
            return first
        return C.link(R, out, objs, LDFLAGS, os.path.dirname(out))
    return C.cached_program(R, "qjs-hcc", [C.compiler_fingerprint(R, cc_argv), src_hash(d), " ".join(flags(suite, cc_argv))], build)


META_RE = re.compile(r"/\*---(.*?)---\*/", re.S)


def parse_meta(text):
    """Minimal test262 front matter parser: includes, flags, features, negative.type/phase."""
    m = META_RE.search(text)
    meta = {"includes": [], "flags": [], "features": [], "negative": None}
    if not m:
        return meta
    body = m.group(1)
    for key in ("includes", "flags", "features"):
        km = re.search(r"^%s:\s*(\[[^\]]*\]|(?:\n\s+-\s*.+)+)" % key, body, re.M)
        if km:
            meta[key] = re.findall(r"[\w.\-/]+", km.group(1))
    nm = re.search(r"^negative:\s*\n((?:\s+.+\n?)+)", body, re.M)
    if nm:
        meta["negative"] = dict(re.findall(r"(\w+):\s*(\w+)", nm.group(1)))
    return meta


def harness_dir(suite):
    return os.path.join(suite.dir, "test262-harness")


def assemble_test262(suite, path):
    """Return (script text, meta) for a test262 test file, following INTERPRETING.md."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    meta = parse_meta(text)
    flags = meta["flags"]
    parts = []
    if "raw" not in flags:
        names = ["assert.js", "sta.js"]
        if "async" in flags:
            names.append("doneprintHandle.js")
        names += [n for n in meta["includes"] if n not in names]
        for n in names:
            with open(os.path.join(harness_dir(suite), n), encoding="utf-8") as f:
                parts.append(f.read())
    body = ("\"use strict\";\n" if "onlyStrict" in flags else "") + "\n".join(parts) + "\n" + text
    return body, meta


def run_262(R, qjs, suite, rel, work):
    script, meta = assemble_test262(suite, os.path.join(suite.dir, rel))
    path = os.path.join(work, "t.js")
    with open(path, "w", encoding="utf-8") as f:
        f.write(script)
    r = C.run_and_capture(R, [qjs, "t.js"], 60, work, env=dict(os.environ, TZ="UTC", LC_ALL="C"))
    r["out"] = r["out"] + "\n[stderr]\n" + r["err"]
    r["err"] = r["err"][-800:]
    return r


def source_for_rt(R, suite, f):
    return os.path.join(source_dir(), f + ".c")


def ref_rt(R, suite):
    d = source_dir()
    objs = [C.gcc_object(gflags(suite), os.path.join(d, f + ".c"), "quickjs/" + f) for f in RT]

    def build(out):
        return C.link(R, out, objs, LDFLAGS, os.path.dirname(out))
    path, fail = C.cached_program(R, "rt262-ref", [C.gcc_fingerprint(), src_hash(d), " ".join(gflags(suite))], build)
    if fail:
        raise RuntimeError("reference run-test262 failed to link: " + fail.reason)
    return path


def hcc_rt(R, suite, cc_argv):
    d = source_dir()

    def build(out):
        objs, first = [], None
        for f in RT:
            obj, fail = C.cached_object(R, cc_argv, flags(suite, cc_argv), os.path.join(d, f + ".c"), "quickjs/" + f, 3600)
            if fail:
                first = first or C.Failure(fail.status, fail.stage, "quickjs build: %s.c: %s" % (f, fail.reason), fail.log)
            else:
                objs.append(obj)
        if first:
            return first
        return C.link(R, out, objs, LDFLAGS, os.path.dirname(out))
    return C.cached_program(R, "rt262-hcc", [C.compiler_fingerprint(R, cc_argv), src_hash(d), " ".join(flags(suite, cc_argv))], build)


def run_rt262(R, rt, suite, rel, work):
    """Run one test262x file with run-test262 (config: harness dir = the suite's copy)."""
    conf = os.path.join(work, "test262.conf")
    with open(os.path.join(source_dir(), "test262.conf")) as f:
        lines = [l for l in f.read().splitlines() if not re.match(r"(testdir|errorfile|reportfile|harnessdir)=", l)]
    lines.insert(1, "harnessdir=" + harness_dir(suite))
    with open(conf, "w") as f:
        f.write("\n".join(lines) + "\n")
    r = C.run_and_capture(R, [rt, "-c", conf, "-v", "-f", os.path.join(suite.dir, rel)], 120, work,
                          env=dict(os.environ, TZ="UTC", LC_ALL="C"))
    r["out"] = (r["out"] + "\n[stderr]\n" + r["err"]).replace(suite.dir, "<SUITE>").replace(work, "<WORK>")
    r["err"] = r["err"][-800:]
    return r


def run_js(R, qjs, suite, rel, work):
    """Run js test `rel` with qjs in a private copy of the js tree."""
    tree = os.path.join(work, "js")
    shutil.copytree(os.path.join(suite.dir, "js"), tree)
    full = os.path.join(tree, rel[len("js/"):])
    argv = [qjs]
    if os.path.basename(rel) in STD_FLAG:
        argv += ["--std"]
    elif "/upstream/" not in rel:
        argv += ["--std", "-I", os.path.join(tree, "_prelude.js")]
    argv += [os.path.basename(full)]
    env = dict(os.environ, TZ="UTC", LC_ALL="C")
    r = C.run_and_capture(R, argv, RUN_TIMEOUT, os.path.dirname(full), env=env)
    r["out"] = (r["out"] + "\n[stderr]\n" + r["err"]).replace(tree, "<TREE>")
    r["err"] = r["err"][-800:]
    return r


def run_test(suite, rel, cc_argv, work, R):
    if rel == "build/run-test262.c":
        obj, fail = C.cached_object(R, cc_argv, flags(suite, cc_argv), os.path.join(source_dir(), "run-test262.c"), "quickjs/run-test262", 3600)
        return fail.result(R) if fail else R.Result("PASS")
    if rel.startswith("test262x/"):
        rt, fail = hcc_rt(R, suite, cc_argv)
        if fail:
            return fail.result(R)
        ref = ref_rt(R, suite)
        want = C.cached_value("rt262-ref-run", [C.gcc_fingerprint(), C.file_sha(ref), C.file_sha(os.path.join(suite.dir, rel)), C.file_sha(__file__)],
                              lambda: run_rt262(R, ref, suite, rel, _tmp(work, "ref")))
        got = run_rt262(R, rt, suite, rel, _tmp(work, "got"))
        return C.compare_runs(R, got, want)
    if rel.startswith("build/") and rel != "build/version":
        f = os.path.basename(rel)[:-2]
        obj, fail = hcc_object(R, suite, cc_argv, f)
        return fail.result(R) if fail else R.Result("PASS")
    qjs, fail = hcc_qjs(R, suite, cc_argv)
    if fail:
        return fail.result(R)
    ref = ref_qjs(R, suite)
    if rel == "build/version":
        script = os.path.join(work, "version.js")
        with open(script, "w") as f:
            f.write("console.log(1 + 1, [1, 2, 3].map(x => x * 2), JSON.stringify({a: 1}));\n")
        env = dict(os.environ, TZ="UTC")
        got = C.run_and_capture(R, [qjs, script], 60, work, env=env)
        want = C.run_and_capture(R, [ref, script], 60, work, env=env)
        return C.compare_runs(R, got, want)
    fn = run_262 if rel.startswith("test262/") else run_js
    want = C.cached_value("qjs-ref-run", [C.gcc_fingerprint(), C.file_sha(ref), C.file_sha(os.path.join(suite.dir, rel)), C.file_sha(__file__)],
                          lambda: fn(R, ref, suite, rel, _tmp(work, "ref")))
    got = fn(R, qjs, suite, rel, _tmp(work, "got"))
    return C.compare_runs(R, got, want)


def _tmp(work, name):
    d = os.path.join(work, name)
    os.makedirs(d, exist_ok=True)
    return d
