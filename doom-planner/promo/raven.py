"""Draw Muninn, a pixel-art raven facing left, as a PNG (one sprite pixel = SCALE px)."""
import sys
from PIL import Image

SPRITE = """
........................................
...........KKKKK........................
.........KKKKKKKKK......................
........KKKKKKKKKKK.....................
.......KKKAYKKKKKKKK....................
...bbbBKKAAKKKKKKKKK....................
.bbbbBBBKKKKKKKKKKKKK...................
...bBBBBKKKKKKKKKKKKKK..................
......BBKKKKKKKKKKKKKKK.................
........KKKKKKKKKKKKKKKK................
.........KKKKKDKKKKKKKKKKK..............
.........KKKKKKDDKKKKKKKKKKK............
.........KKKKKKKGDDKKKKKKKKKKK..........
..........KKKKKKKKGDDDKKKKKKKKKKK.......
..........KKKKKKKKKKGGDDDKKKKKKKKKKK....
...........KKKKKKKKKKKKGGDDDKKKKKKKKKKK.
...........KKKKKKKKKKKKKKKGGDDKKKKKKKKKK
............KKKKKKKKKKKKKKKKKGGDKKKKKKK.
.............KKKKKKKKKKKKKKKKKKKKKKKK...
..............KKKKKKKKKKKKKKKKKKKKK.....
................KKKKKKKKKKKKKKKKK.......
..................KKKKKKKKKKKK..........
....................LL...LL.............
....................LL...LL.............
...................LLLL.LLLL............
""".strip("\n").splitlines()

PALETTE = {
    "K": (14, 11, 12, 255), "D": (36, 30, 33, 255), "G": (75, 65, 70, 255),
    "B": (60, 53, 55, 255), "b": (94, 85, 88, 255), "A": (242, 163, 58, 255),
    "Y": (255, 224, 138, 255), "L": (107, 90, 64, 255),
}


def main(out, scale=14):
    w = max(len(r) for r in SPRITE)
    img = Image.new("RGBA", (w, len(SPRITE)), (0, 0, 0, 0))
    for y, row in enumerate(SPRITE):
        for x, ch in enumerate(row):
            if ch in PALETTE:
                img.putpixel((x, y), PALETTE[ch])
    img.resize((w * scale, len(SPRITE) * scale), Image.NEAREST).save(out)


if __name__ == "__main__":
    main(sys.argv[1])
