"""Sub-minute fixture: RESULTS.md must match results/*.json.

Every table in RESULTS.md is generated by make_tables.py, so this regenerates
them and asserts the exact text is present. CLAIMS holds the prose figures that
are not in a table, each with the JSON path it comes from.
"""
import json, os, sys
import make_tables

OUT = os.path.dirname(os.path.abspath(__file__))
RES = f"{OUT}/results"

# (sentence fragment that must appear in RESULTS.md, json file, dotted path, fmt)
CLAIMS = [
    ("BM25 alone scores {} HIT@10",                "A2_whole_doc.json",   "overall.hit10",   ".2f"),
    ("Recall@10 {} against",                       "A2_whole_doc_plain.json", "overall.recall10", ".2f"),
    ("BM25 rescues **{}%** of the dense arm's",    "analysis.json", "rescue.A1s_chunked_sub_rescues_B_dense_sub.rate", ""),
    ("Dense rescues\n**{}%** of BM25's",           "analysis.json", "rescue.B_dense_sub_rescues_A1s_chunked_sub.rate", ""),
    ("rescues\n**{}%** of the hybrid's misses",    "analysis.json", "rescue.A1s_chunked_sub_rw_rescues_C_rrf_A1s_B.rate", ""),
    ("`rrf(A1s, B)` scores {} against",            "analysis.json", "arms.C_rrf_A1s_B.hit10", ".2f"),
    ("Adding both S4 rewrite legs takes it to {}", "analysis.json", "arms.D_rrf_all.hit10",   ".2f"),
    ("BM25 drops from 81.06 to {} ",               "analysis.json", "arms.A1s_chunked_sub_rw.hit10", ".2f"),
    ("mean is {}%",                                "overlap.json",  "_ALL.mean_term_coverage", ".1f"),
]

def main():
    md = open(f"{OUT}/RESULTS.md").read()
    fails = []

    for name, block in make_tables.render().items():
        if block not in md:
            fails.append(f"table {name} in RESULTS.md does not match results/*.json")

    for frag, fname, path, fmt in CLAIMS:
        d = json.load(open(f"{RES}/{fname}"))
        for k in path.split("."):
            d = d[k]
        want = frag.replace("{}", format(d, fmt))
        if want not in md:
            fails.append(f"claim not found verbatim: {want!r}")

    if fails:
        print("RECHECK FAILED")
        for f in fails:
            print("  -", f)
        return 1
    print(f"recheck ok: {len(make_tables.render())} tables, {len(CLAIMS)} claims")
    return 0

if __name__ == "__main__":
    sys.exit(main())
