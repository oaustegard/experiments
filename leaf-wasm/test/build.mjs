// Generate the matmul kernel (web/kernel*.wat) and assemble it (web/kernel*.wasm, committed so
// the page needs no assembler). Two builds of one module:
//   kernel-fma.wasm  f32x4.relaxed_madd (relaxed SIMD: Chrome 114+, Node 20+)
//   kernel.wasm      f32x4.mul + f32x4.add (any browser with SIMD128)
// Each exports mm (4 x 16 register tile, N % 16 == 0) and mm4 (4 x 4, N % 4 == 0); both
// compute Y[S,N] = X[S,K] W[K,N] (+ b[N]), f32 row-major, pointers in bytes, S % 4 == 0.
// The 4 x 16 tile reuses each splatted x across four weight vectors: ~1.7-2x the 4 x 4 tile
// on an M1 (21 of 32 NEON registers live); 4 x 32 spills and is slower.
import { writeFileSync } from "node:fs";
import wabtInit from "wabt";

function func(name, C, fma) {
  const v = (n) => `(local.get $${n})`;
  const acc = [], body = [], init = [], stores = [];
  for (let r = 0; r < 4; r++) for (let c = 0; c < C; c++) acc.push(`(local $a${r}${c} v128)`);
  const xAt = (r) => (r ? `(i32.add ${v("xr")} (i32.mul ${v("xo")} (i32.const ${r})))` : v("xr"));
  for (let c = 0; c < C; c++) body.push(`(local.set $w${c} (v128.load offset=${16 * c} ${v("wk")}))`);
  for (let r = 0; r < 4; r++) {
    body.push(`(local.set $xs (v128.load32_splat ${xAt(r)}))`);
    for (let c = 0; c < C; c++)
      body.push(fma ? `(local.set $a${r}${c} (f32x4.relaxed_madd ${v(`w${c}`)} ${v("xs")} ${v(`a${r}${c}`)}))`
                    : `(local.set $a${r}${c} (f32x4.add ${v(`a${r}${c}`)} (f32x4.mul ${v(`w${c}`)} ${v("xs")})))`);
  }
  for (let c = 0; c < C; c++)
    init.push(`(if ${v("b")} (then (local.set $a0${c} (v128.load offset=${16 * c} (i32.add ${v("b")} (i32.shl ${v("n")} (i32.const 2))))))
      (else (local.set $a0${c} (v128.const i32x4 0 0 0 0))))`);
  for (let r = 1; r < 4; r++) for (let c = 0; c < C; c++) init.push(`(local.set $a${r}${c} ${v(`a0${c}`)})`);
  for (let r = 0; r < 4; r++) for (let c = 0; c < C; c++)
    stores.push(`(v128.store offset=${16 * c} (i32.add ${v("yr")} (i32.mul (i32.shl ${v("N")} (i32.const 2)) (i32.const ${r}))) ${v(`a${r}${c}`)})`);
  const ws = Array.from({ length: C }, (_, c) => `(local $w${c} v128)`).join(" ");
  return ` (func (export "${name}") (param $x i32) (param $w i32) (param $y i32) (param $b i32) (param $S i32) (param $K i32) (param $N i32)
  (local $s i32) (local $k i32) (local $n i32) (local $wk i32) (local $xr i32) (local $yr i32) (local $xo i32) (local $xs v128)
  ${ws}
  ${acc.join(" ")}
  (local.set $xo (i32.shl ${v("K")} (i32.const 2)))
  (local.set $s (i32.const 0))
  (block $sd (loop $sl (br_if $sd (i32.ge_u ${v("s")} ${v("S")}))
   (local.set $n (i32.const 0))
   (block $nd (loop $nl (br_if $nd (i32.ge_u ${v("n")} ${v("N")}))
    ${init.join("\n    ")}
    (local.set $xr (i32.add ${v("x")} (i32.mul ${v("s")} ${v("xo")})))
    (local.set $wk (i32.add ${v("w")} (i32.shl ${v("n")} (i32.const 2))))
    (local.set $k (i32.const 0))
    (block $kd (loop $kl (br_if $kd (i32.ge_u ${v("k")} ${v("K")}))
     ${body.join("\n     ")}
     (local.set $xr (i32.add ${v("xr")} (i32.const 4)))
     (local.set $wk (i32.add ${v("wk")} (i32.shl ${v("N")} (i32.const 2))))
     (local.set $k (i32.add ${v("k")} (i32.const 1)))
     (br $kl)))
    (local.set $yr (i32.add ${v("y")} (i32.shl (i32.add (i32.mul ${v("s")} ${v("N")}) ${v("n")}) (i32.const 2))))
    ${stores.join("\n    ")}
    (local.set $n (i32.add ${v("n")} (i32.const ${4 * C})))
    (br $nl)))
   (local.set $s (i32.add ${v("s")} (i32.const 4)))
   (br $sl))))`;
}

const dir = new URL("../web/", import.meta.url);
const wabt = await wabtInit();
for (const [file, fma] of [["kernel", false], ["kernel-fma", true]]) {
  const wat = `;; Generated by test/build.mjs. Do not edit.\n(module\n (import "env" "mem" (memory 1))\n${func("mm", 4, fma)}\n${func("mm4", 1, fma)})\n`;
  writeFileSync(new URL(`${file}.wat`, dir), wat);
  const mod = wabt.parseWat(`${file}.wat`, wat, { simd: true, relaxed_simd: fma });
  mod.validate();
  const { buffer } = mod.toBinary({});
  writeFileSync(new URL(`${file}.wasm`, dir), buffer);
  console.log(`${file}.wasm ${buffer.byteLength} bytes`);
}
