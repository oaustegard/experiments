RESULTS = ROOT / "results/sweep.json"
DATA = ROOT / "data"
THREADS = 2
BOOT_N, BOOT_SEED, ALPHA = 4000, 20261124, 0.05
# t4r127 is not in the brief's list: t4r63 fails and so does r63, which leaves the head's 4 bits untested
REC_ARMS = {"f16": ("f16", None), "r127": ("r127", None), "r63": ("r63", None), "r31": ("r31", None),
            "t4r63": ("r63", "t4"), "t4r127": ("r127", "t4")}
DET_ARMS = {k: v for k, v in REC_ARMS.items() if not k.startswith("t4")}
DET_PAGES_SYNTH = ["text_two_column", "heading_table", "dense_small"]
N_FUNSD_PAGES = 17
LONG = 1280


def sess_of(model_bytes):
    so = ort.SessionOptions()
    so.intra_op_num_threads = THREADS
    so.inter_op_num_threads = 1
    return ort.InferenceSession(model_bytes, so, providers=["CPUExecutionProvider"])


def load_results():
    return json.loads(RESULTS.read_text()) if RESULTS.exists() else {}


def save_results(res):
    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    tmp = RESULTS.with_suffix(".tmp")
    tmp.write_text(json.dumps(res, indent=1, ensure_ascii=False) + "\n")
    tmp.replace(RESULTS)


class Clock:
    def __init__(self, budget):
        self.t0, self.budget = time.time(), budget

    def out(self):
        return time.time() - self.t0 > self.budget


# ------------------------------------------------------------------ recognizer


class Rec(ppc.PPRec):
    """PPRec with its session supplied and its preprocessing served from a cache (same prep, run once per line)."""

    def __init__(self, chars, sess, cache):
        self.chars, self.sess, self.cache = chars, sess, cache

    def prep(self, path):
        if path not in self.cache:
            self.cache[path] = ppc.PPRec.prep(self, path)
        return self.cache[path]


def select_lines(per_cond):
    """Stratified, seeded subsample of the synthetic set (per_cond lines per degradation condition; 0 = all)
    plus every real line. Returns {set_name: rows}; sets: synth, real (FUNSD), sroie."""
    synth = ppc.load_rows("synth")
    if per_cond:
        rng = np.random.default_rng(BOOT_SEED)
        keep = []
        for cond in sorted({r["cond"] for r in synth}):
            rows = [r for r in synth if r["cond"] == cond]
            keep += [rows[i] for i in sorted(rng.choice(len(rows), min(per_cond, len(rows)), replace=False))]
        synth = keep
    real = ppc.load_rows("real")
    return {"synth": synth, "real": [r for r in real if r["set"] == "funsd"],
            "sroie": [r for r in real if r["set"] == "sroie"]}


def rec_predictions(model, arm, sets, rec, clock, ckpt):
    """Fill ckpt/<arm>.jsonl with {file, pred} for every line of every set. Returns True when complete."""
    ckpt.mkdir(parents=True, exist_ok=True)
    path = ckpt / f"{arm}.jsonl"
    done = {}
    if path.exists():
        for l in open(path, encoding="utf-8"):
            r = json.loads(l)
            done[r["file"]] = r
    todo = [r for rows in sets.values() for r in rows if r["file"] not in done]
    if not todo:
        return True
    t0 = time.time()
    with open(path, "a", encoding="utf-8") as f:
        for i, r in enumerate(todo):
            try:
                pred = rec.read(r["path"])
            except Exception as e:  # recorded and excluded, never scored as an empty reading
                pred = None
                print(f"{model} {arm} {r['file']}: {e!r}", file=sys.stderr)
            f.write(json.dumps({"file": r["file"], "pred": pred}, ensure_ascii=False) + "\n")
            if i % 100 == 99:
                f.flush()
                if clock.out():
                    print(f"  rec {model} {arm}: {i + 1}/{len(todo)} lines, {time.time() - t0:.0f}s, out of budget")
                    return False
    print(f"  rec {model} {arm}: {len(todo)} lines in {time.time() - t0:.0f}s")
    return True


def read_preds(ckpt, arm):
    out = {}
    for l in open(ckpt / f"{arm}.jsonl", encoding="utf-8"):
        r = json.loads(l)
        out[r["file"]] = r["pred"]
    return out


def boot_ci(d):
    """95% percentile bootstrap CI of the mean of d (paired differences), resampling lines."""
    rng = np.random.default_rng(BOOT_SEED)
    n, means = len(d), []
    for _ in range(BOOT_N // 500):
        idx = rng.integers(0, n, (500, n))
        means.append(d[idx].mean(axis=1))
    m = np.concatenate(means)
    return float(np.percentile(m, 100 * ALPHA / 2)), float(np.percentile(m, 100 * (1 - ALPHA / 2)))


def rec_metrics(rows, ref, pred):
    """rows of one set (with text), ref/pred {file: text or None}. Lines either reading failed on are dropped."""
    use = [r for r in rows if ref.get(r["file"]) is not None and pred.get(r["file"]) is not None]
    c_ref = np.array([cer(r["text"], ref[r["file"]]) for r in use])
    c_arm = np.array([cer(r["text"], pred[r["file"]]) for r in use])
    d = c_arm - c_ref
    lo, hi = boot_ci(d)
    same = np.array([ref[r["file"]] == pred[r["file"]] for r in use])
    return {"n": len(use), "n_failed": len(rows) - len(use), "cer": round(float(c_arm.mean()), 6),
            "cer_fp32": round(float(c_ref.mean()), 6), "delta": round(float(d.mean()), 6),
            "delta_ci": [round(lo, 6), round(hi, 6)], "identical": round(float(same.mean()), 5),
            "n_changed": int((~same).sum())}


def rec_ok(m):
    return (m["delta_ci"][0] <= 0 <= m["delta_ci"][1]) or m["identical"] >= 0.99


def sets_for_metrics(sets):
    return {"synth": sets["synth"], "synth_latin": [r for r in sets["synth"] if r["lang"] in ("eng", "fra")],
            "real": sets["real"], "sroie": sets["sroie"]}


# The decision looks at the sets PP-OCRv6 can read. The synthetic set's Greek quarter reads at 55-71% CER in fp32
# (tesseract-gpu pp_rec_compare), so any perturbation reshuffles that garbage; `synth` is reported and has its
# own flag (pass_with_synth_all) but does not gate the decision.
DECISION_SETS = ("synth_latin", "real")


def fold_check(model, folded, rows, chars, cache):
    """The fp32 reference is the BN-folded graph. Against the upstream graph on the FUNSD lines: max |logit diff|
    and the share of identical decoded text."""
    a = Rec(chars, sess_of(open(ROOT / "models" / f"{model}_rec/inference.onnx", "rb").read()), cache)
    b = Rec(chars, sess_of(quant.pack(folded, "f32").onnx_bytes()), cache)
    worst, same = 0.0, 0
    for r in rows:
        x = a.prep(r["path"])
        worst = max(worst, float(np.abs(a.sess.run(None, {"x": x})[0] - b.sess.run(None, {"x": x})[0]).max()))
        same += a.read(r["path"]) == b.read(r["path"])
    return {"lines": len(rows), "max_abs_logit_diff": worst, "identical": round(same / len(rows), 5)}


def run_rec(model, folded, sets, clock, res, ckpt):
    chars_cfg = yaml.safe_load(open(ROOT / "models" / f"{model}_rec/inference.yml"))
    chars = ["<blank>"] + list(chars_cfg["PostProcess"]["character_dict"]) + [" "]
    cache = {}
    node = res["models"][model]["rec"]
    complete = True
    if "fold_check" not in node:
        node["fold_check"] = fold_check(model, folded, sets["real"], chars, cache)
    for arm, (scheme, head) in [("f32", ("f32", None))] + list(REC_ARMS.items()):
        pk = quant.pack(folded, scheme, head)
        if arm != "f32":
            node["arms"].setdefault(arm, {})["size"] = {**pk.sizes, **pk.werr}
        else:
            node["fp32_folded_size"] = pk.sizes
        if not rec_predictions(model, arm, sets, Rec(chars, sess_of(pk.onnx_bytes()), cache), clock, ckpt):
            complete = False
            break
    if complete or (ckpt / "f32.jsonl").exists():
        ref = read_preds(ckpt, "f32")
        node["lines"] = {k: len(v) for k, v in sets_for_metrics(sets).items()}
        node["fp32"] = {k: {"cer": round(float(np.mean([cer(r["text"], ref[r["file"]]) for r in rows if ref.get(r["file"]) is not None])), 6),
                            "n": sum(1 for r in rows if ref.get(r["file"]) is not None)}
                        for k, rows in sets_for_metrics(sets).items()}
        ref_pool = [cer(r["text"], ref[r["file"]]) for r in sets["real"] + sets["sroie"] if ref.get(r["file"]) is not None]
        prior = [x["mean_cer"] for x in json.load(open(TESS / "results/pp_rec_compare.json"))["rows"]
                 if x["set"] == "real" and x["cond"] == "all" and x["reader"] == f"pp_{model}"]
        node["validation"] = {"fp32_cer_all_real_lines": round(float(np.mean(ref_pool)), 5), "n": len(ref_pool),
                              "tesseract_gpu_pp_rec_compare_real": prior[0] if prior else None}
        for arm in REC_ARMS:
            p = ckpt / f"{arm}.jsonl"
            if not p.exists():
                continue
            pred = read_preds(ckpt, arm)
            if any(r["file"] not in pred for rows in sets.values() for r in rows):
                continue
            a = node["arms"][arm]
            for k, rows in sets_for_metrics(sets).items():
                a[k] = rec_metrics(rows, ref, pred)
            a["ok"] = {k: rec_ok(a[k]) for k in ("synth", "synth_latin", "real", "sroie")}
            a["pass"] = all(a["ok"][k] for k in DECISION_SETS)
            a["pass_with_synth_all"] = a["pass"] and a["ok"]["synth"]
    return complete


# ------------------------------------------------------------------ detector


def load_pages():
    from PIL import Image
    import io
    import pyarrow.parquet as pq
    pages = {}
    for name in DET_PAGES_SYNTH:
        pages[name] = np.asarray(Image.open(TESS / "data/det_pages" / f"{name}.png").convert("RGB"))
    t = pq.read_table(TESS / "data/det_funsd_raw/test.parquet", columns=["id", "image"])
    for i in range(N_FUNSD_PAGES):
        blob = t.column("image")[i].as_py()["bytes"]
        pages[f"funsd_{i}"] = np.asarray(Image.open(io.BytesIO(blob)).convert("RGB"))
    return pages


def db_boxes(pred, post):
    """PaddleOCR DBPostProcess.boxes_from_bitmap on one probability map (h, w); boxes in map pixels."""
    import cv2
    import pyclipper
    from shapely.geometry import Polygon

    def mini(contour):
        rect = cv2.minAreaRect(contour)
        pts = sorted(cv2.boxPoints(rect).tolist(), key=lambda p: p[0])
        i1, i4 = (0, 1) if pts[1][1] > pts[0][1] else (1, 0)
        i2, i3 = (2, 3) if pts[3][1] > pts[2][1] else (3, 2)
        return [pts[i1], pts[i2], pts[i3], pts[i4]], min(rect[1])

    def score(box):
        h, w = pred.shape
        b = box.copy()
        x0, x1 = np.clip(np.floor(b[:, 0].min()).astype(int), 0, w - 1), np.clip(np.ceil(b[:, 0].max()).astype(int), 0, w - 1)
        y0, y1 = np.clip(np.floor(b[:, 1].min()).astype(int), 0, h - 1), np.clip(np.ceil(b[:, 1].max()).astype(int), 0, h - 1)
        mask = np.zeros((y1 - y0 + 1, x1 - x0 + 1), np.uint8)
        b[:, 0] -= x0
        b[:, 1] -= y0
        cv2.fillPoly(mask, b.reshape(1, -1, 2).astype(np.int32), 1)
        return cv2.mean(pred[y0:y1 + 1, x0:x1 + 1], mask)[0]

    bitmap = (pred > post["thresh"]).astype(np.uint8)
    contours, _ = cv2.findContours(bitmap * 255, cv2.RETR_LIST, cv2.CHAIN_APPROX_SIMPLE)
    boxes = []
    for c in contours[:post["max_candidates"]]:
        pts, side = mini(c)
        if side < 3:
            continue
        pts = np.array(pts, np.float32)
        if score(pts) < post["box_thresh"]:
            continue
        poly = Polygon(pts)
        if poly.length == 0:
            continue
        off = pyclipper.PyclipperOffset()
        off.AddPath(pts.astype(np.int64).tolist(), pyclipper.JT_ROUND, pyclipper.ET_CLOSEDPOLYGON)
        grown = off.Execute(poly.area * post["unclip_ratio"] / poly.length)
        if not grown:
            continue
        box, side = mini(np.array(grown[0], np.float32).reshape(-1, 1, 2))
        if side < 5:
            continue
        boxes.append(np.array(box, np.float32))
    return boxes


def match(ref, got, iou_min=0.5):
    """Greedy one-to-one matching by descending polygon IoU. Returns the number of matches."""
    from shapely.geometry import Polygon
    if not ref or not got:
        return 0
    pr, pg = [Polygon(b).buffer(0) for b in ref], [Polygon(b).buffer(0) for b in got]
    br, bg = np.array([p.bounds for p in pr]), np.array([p.bounds for p in pg])
    pairs = []
    for i, a in enumerate(pr):
        near = np.where((bg[:, 0] < br[i, 2]) & (bg[:, 2] > br[i, 0]) & (bg[:, 1] < br[i, 3]) & (bg[:, 3] > br[i, 1]))[0]
        for j in near:
            inter = a.intersection(pg[j]).area
            iou = inter / (a.area + pg[j].area - inter) if inter > 0 else 0.0
            if iou >= iou_min:
                pairs.append((iou, i, j))
    used_i, used_j, n = set(), set(), 0
    for iou, i, j in sorted(pairs, reverse=True):
        if i not in used_i and j not in used_j:
            used_i.add(i)
            used_j.add(j)
            n += 1
    return n


def run_det(model, folded, clock, res):
    cfg = yaml.safe_load(open(ROOT / "models" / f"{model}_det/inference.yml"))
    post = cfg["PostProcess"]
    ops = {next(iter(o)): o[next(iter(o))] for o in cfg["PreProcess"]["transform_ops"]}
    norm = ops["NormalizeImage"]
    mean, std = norm["mean"], norm["std"]
    node = res["models"][model]["det"]
    node["post"] = {k: post[k] for k in ("thresh", "box_thresh", "unclip_ratio", "max_candidates")}
    pages = load_pages()
    prep = {}
    for name, rgb in pages.items():
        x, _, h1, w1 = ref_det.preprocess(rgb, LONG, mean, std)
        prep[name] = (x[None], h1, w1)

    def maps(sess):
        out = {}
        for name, (x, h1, w1) in prep.items():
            out[name] = sess.run(None, {"x": x})[0][0, 0, :h1, :w1]
        return out

    ref_pk = quant.pack(folded, "f32")
    node["fp32_folded_size"] = ref_pk.sizes
    ref_maps = maps(sess_of(ref_pk.onnx_bytes()))
    ref_boxes = {n: db_boxes(m, post) for n, m in ref_maps.items()}
    node["pages"] = {n: {"h": prep[n][1], "w": prep[n][2], "n_boxes_fp32": len(ref_boxes[n])} for n in pages}
    node["n_pages"] = len(pages)
    complete = True
    for arm, (scheme, head) in DET_ARMS.items():
        pk = quant.pack(folded, scheme, head)
        a = node["arms"].setdefault(arm, {})
        a["size"] = {**pk.sizes, **pk.werr}
        if "box_f1" in a:
            continue
        if clock.out():
            complete = False
            continue
        t0 = time.time()
        got_maps = maps(sess_of(pk.onnx_bytes()))
        per, tp = {}, [0, 0, 0]
        for n in pages:
            diff = np.abs(got_maps[n] - ref_maps[n])
            boxes = db_boxes(got_maps[n], post)
            m = match(ref_boxes[n], boxes)
            nr, ng = len(ref_boxes[n]), len(boxes)
            f1 = 1.0 if nr == ng == 0 else 2 * m / (nr + ng)
            per[n] = {"max_abs_diff": float(diff.max()), "mask_flip_share": float(((got_maps[n] > post["thresh"]) != (ref_maps[n] > post["thresh"])).mean()),
                      "n_ref": nr, "n_arm": ng, "matched": m, "f1": round(f1, 5)}
            tp[0] += m
            tp[1] += nr
            tp[2] += ng
        a.update({"max_abs_diff": max(p["max_abs_diff"] for p in per.values()),
                  "mean_abs_diff": float(np.mean([np.abs(got_maps[n] - ref_maps[n]).mean() for n in pages])),
                  "mask_flip_share": float(np.mean([p["mask_flip_share"] for p in per.values()])),
                  "box_f1": round(2 * tp[0] / (tp[1] + tp[2]), 5), "box_f1_min_page": min(p["f1"] for p in per.values()),
                  "matched": tp[0], "n_boxes_fp32": tp[1], "n_boxes_arm": tp[2], "pages": per})
        a["pass"] = a["box_f1"] >= 0.99
        print(f"  det {model} {arm}: F1 {a['box_f1']:.4f} max|d| {a['max_abs_diff']:.2e} ({time.time() - t0:.0f}s)")
    return complete


# ------------------------------------------------------------------ decision


def decide(node, flag="pass"):
    """Smallest arm (by gzip -9 bytes, then packed bytes) whose `flag` is true; None if none is."""
    ok = [(a["size"]["gzip9_bytes"], a["size"]["packed_bytes"], k) for k, a in node["arms"].items() if a.get(flag)]
    return min(ok)[2] if ok else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model", choices=["tiny", "small"])
    ap.add_argument("--part", choices=["rec", "det", "both"], default="both")
    ap.add_argument("--budget", type=float, default=1e9, help="seconds before stopping at the next checkpoint")
    ap.add_argument("--synth-per-cond", type=int, default=0, help="synthetic lines per condition (0 = every generated line)")
    a = ap.parse_args()
    clock = Clock(a.budget)
    res = load_results()
    res["meta"] = {
        "what": "cost of the ppocr-pack weight format on PP-OCRv6 tiny/small, onnxruntime CPU fake-quantisation",
        "onnxruntime": ort.__version__, "threads": THREADS,
        "cer": "mean per-line CER as a fraction (0.01 = 1%); delta = arm minus fp32 on the same lines; delta_ci = 95% paired bootstrap over lines",
        "bootstrap": {"resamples": BOOT_N, "seed": BOOT_SEED}, "identical": "share of lines whose decoded text equals fp32's, exact string",
        "rec_sets": {"synth": "tesseract-gpu data/lines (stratified sample, see rec.lines), eng+fra+grc",
                     "synth_latin": "synth, eng+fra only (PP-OCRv6 does not read Greek)",
                     "real": "tesseract-gpu data/real, FUNSD crops", "sroie": "tesseract-gpu data/real, SROIE receipt lines (supplementary)"},
        "det_pages": f"{len(DET_PAGES_SYNTH)} synthetic + {N_FUNSD_PAGES} FUNSD test pages, long side {LONG}",
        "rule": {"rec": "per set: CER delta CI contains 0 or identical >= 0.99; an arm passes when every set in decision_sets does (pass_with_synth_all adds the full synthetic set)",
                 "det": "box F1 vs fp32 >= 0.99", "decision_sets": list(DECISION_SETS),
                 "smallest": "least gzip -9 bytes, then packed bytes"},
        "formats": "see run/quant.py",
        "notes": [
            "fp32 is the BN-folded graph (rec.fold_check: identical decoded text to the upstream graph; the detectors have no BatchNorm left)",
            "f16 stores every packable tensor (>= 1,024 elements) as fp16; biases and smaller tensors stay fp32",
            "ConvTranspose weights [I, O/g, kh, kw] are scaled per output channel, which is axis 1; per model one is packed (16x16x2x2 tiny, 24x24x2x2 small) and the 16x1x2x2 / 24x1x2x2 one stays fp32",
            "t4r127 (4-bit head, other weights r127) is not in the brief: it separates the head's 4 bits from r63's body, which fails alone",
            "sizes count the byte stream of run/quant.py (codes, fp16 scales, fp32 rest), not graph structure or integer constants",
            "synthetic lines: every generated line (4,800 = 600 base lines x 8 conditions), not a 600-line cap, because generation took minutes and the sweep seconds per arm",
        ],
    }
    node = res.setdefault("models", {}).setdefault(a.model, {"upstream_bytes": {
        k: (ROOT / "models" / f"{a.model}_{k}/inference.onnx").stat().st_size for k in ("det", "rec")}})
    node.setdefault("rec", {}).setdefault("arms", {})
    node.setdefault("det", {}).setdefault("arms", {})
    complete = True
    if a.part in ("rec", "both"):
        folded, rep = quant.load_folded(ROOT / "models" / f"{a.model}_rec/inference.onnx")
        node["rec"]["bn_fold"] = {"folded": len(rep["folded"]), "kept": rep["kept"]}
        sets = select_lines(a.synth_per_cond)
        print(f"{a.model} rec: lines " + ", ".join(f"{k} {len(v)}" for k, v in sets.items()))
        complete &= run_rec(a.model, folded, sets, clock, res, DATA / "preds" / f"{a.model}_rec")
        node["rec"]["decision"] = decide(node["rec"])
        node["rec"]["decision_with_synth_all"] = decide(node["rec"], "pass_with_synth_all")
        save_results(res)
    if a.part in ("det", "both"):
        folded, rep = quant.load_folded(ROOT / "models" / f"{a.model}_det/inference.onnx")
        node["det"]["bn_fold"] = {"folded": len(rep["folded"]), "kept": rep["kept"]}
        if clock.out():
            complete = False
        else:
            complete &= run_det(a.model, folded, clock, res)
        node["det"]["decision"] = decide(node["det"])
        save_results(res)
    print(f"{a.model}: {'complete' if complete else 'INCOMPLETE, rerun to resume'}; rec -> {node['rec'].get('decision')}, det -> {node['det'].get('decision')}")
    return 0 if complete else 3


