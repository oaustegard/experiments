#!/usr/bin/env python3
"""What does the packed-weight format cost PP-OCRv6 tiny and small? Fake-quantised ONNX on onnxruntime CPU.

    python3 -I run/sweep.py tiny                 # det and rec of one model size, every arm
    python3 -I run/sweep.py small --part rec
    python3 -I run/sweep.py tiny --budget 500    # stop cleanly after ~500 s; rerun to resume (exit 3 = unfinished)

Arms (run/quant.py has the format): f16; r127; r63; r31; for the recognizer also t4r63 (CTC head at 4 bits in
groups of 32, every other packable weight r63). fp32 is the reference. Each arm rewrites the folded ONNX
initializers with their dequantised values and runs onnxruntime (CPU, intra_op_num_threads=2).

Recognizer: the line sets of tesseract-gpu (data/lines, data/real, regenerated by that experiment's
make_lines.py and make_real.py), read by tesseract-gpu/run/pp_rec_compare.PPRec (RecResizeImg h48, BGR, (x/255 -
0.5)/0.5, pad to max(320, w), greedy CTC, blank 0, a space appended to the dictionary) and scored with
tess_baseline.cer. Per set: mean CER, change against fp32 with a 95% paired bootstrap CI over lines, and the
share of lines whose decoded text equals fp32's.

Detector: 20 pages (3 synthetic from tesseract-gpu make_pages.py, 17 FUNSD test pages), long side 1280 as
tesseract-gpu/run/ref_det.py preprocesses them. Per arm: max |probability map - fp32|, and box F1 against the
fp32 boxes (PaddleOCR's DB post-process with the thresholds in inference.yml; boxes match at polygon IoU >= 0.5).

Results go to results/sweep.json keyed models.<size>.{det,rec}.arms.<arm>...; per-line predictions are
checkpointed under data/ (git-ignored) so an interrupted run resumes.
"""
