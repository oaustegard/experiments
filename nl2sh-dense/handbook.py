#!/usr/bin/env python3
"""Emit the enriched corpus as a standalone, greppable shell handbook.

`enrich.py` produces `data/cards.jsonl` for a retrieval measurement, but the
cards are worth something on their own: 6,397 command-line utilities each given a
plain-language summary, a task category, the goal-level phrasings someone would
use wanting it, and a short disambiguation against the tools it is confused with
— sitting above the original tldr examples rather than replacing them. That is
documentation organised by what a user wants rather than by what each tool is
called, which is the axis every shell manual is missing and the axis an LLM or a
retrieval tier needs.

Two output shapes, because the useful consumers differ:

* `--format markdown` — one section per utility in a single file, ordered by
  utility name. Greppable with `rg`, chunkable on `##` boundaries, and small
  enough to hand to a model whole in slices.
* `--format jsonl` — one record per utility with a stable schema, for anything
  that wants to index rather than read it.

**Provenance and licence.** The examples are reproduced verbatim from
[tldr-pages](https://github.com/tldr-pages/tldr), copyright the tldr-pages team
and contributors, licensed **CC-BY-4.0**; the man-page material comes from the
manuals installed in the build container and carries each package's own licence.
The summary, category, intents and disambiguation lines are generated by
`gemini-3.5-flash-lite` from those sources and are unreviewed model output — they
are a retrieval aid, not documentation to trust over the real page. This header is
emitted into every artifact so the attribution travels with the file.

    python3 handbook.py --format markdown --out shell_handbook.md
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import dense_index as D  # noqa: E402
import retrieve as R  # noqa: E402

HEADER = """<!--
Shell utility handbook — {n} utilities, generated by nl2sh-dense/handbook.py.

Examples are reproduced verbatim from tldr-pages (https://github.com/tldr-pages/tldr),
(c) the tldr-pages team and contributors, licensed CC-BY-4.0. Man-page material
carries each package's own licence. The summary, category, "use when" and "not
for" lines are generated by gemini-3.5-flash-lite from those sources and are
unreviewed model output: a retrieval aid, not documentation to trust over the
real page.
-->

# Shell utility handbook

{n} command-line utilities, each with a plain-language summary, the goal-level
phrasings someone would use when they want it, and its documented examples.
Organised by what a user wants rather than by what the tool is called.

"""


def sections(pages, cards):
    for p in sorted(pages, key=lambda c: (c.utility.lower(), c.id)):
        yield p, cards.get(p.id)


def as_markdown(pages, cards) -> str:
    out = [HEADER.format(n=len(pages))]
    for p, card in sections(pages, cards):
        out.append(f"## `{p.utility}`\n")
        if card:
            if card.get("summary"):
                out.append(f"{card['summary']}\n")
            if card.get("category"):
                out.append(f"**Category:** {card['category']}\n")
            if card.get("intents"):
                out.append("**Use when you want to:** "
                           + "; ".join(card["intents"]) + "\n")
            if card.get("not_for"):
                out.append("**Not for:** " + "; ".join(card["not_for"]) + "\n")
        else:
            out.append("_No generated summary for this page._\n")
        out.append("```\n" + p.text.strip() + "\n```\n")
    return "\n".join(out)


def as_jsonl(pages, cards) -> str:
    lines = []
    for p, card in sections(pages, cards):
        card = card or {}
        lines.append(json.dumps({
            "utility": p.utility, "source_id": p.id, "source_kind": p.kind,
            "summary": card.get("summary", ""),
            "category": card.get("category", ""),
            "intents": card.get("intents", []),
            "not_for": card.get("not_for", []),
            "documentation": p.text,
            "generated": bool(card),
        }))
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--chunks", type=Path, default=D.DEFAULT_CHUNKS)
    ap.add_argument("--cards", type=Path, default=HERE / "data" / "cards.jsonl")
    ap.add_argument("--format", default="markdown", choices=["markdown", "jsonl"])
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args()

    pages = D.page_chunks(R.load_chunks(a.chunks))
    cards = {}
    if a.cards.is_file():
        for line in a.cards.open():
            rec = json.loads(line)
            if rec.get("card"):
                cards[rec["id"]] = rec["card"]
    text = (as_markdown if a.format == "markdown" else as_jsonl)(pages, cards)
    out = a.out or (HERE / f"shell_handbook.{'md' if a.format == 'markdown' else 'jsonl'}")
    out.write_text(text)
    print(f"wrote {out.name}: {len(pages)} utilities, {len(cards)} with generated "
          f"fields, {len(text) / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
