#!/usr/bin/env python3
"""Decompilation test runner: one suite per translation unit, one test per function.

    python3 tests/run.py --suite S1,S2 [--jobs N] [--json OUT] [--filter GLOB ...] [-v] [--quiet]
                         [--baseline OLD.json]

For each suite <proj>-<tu> it generates the translation unit from the
reconstructed source

    every src/<proj>/types/*.h (sorted)       shared types, one per file
    every src/<proj>/<tu>/*.h (sorted)        TU-local declarations
    every src/<proj>/<tu>/*.c                 one function or variable per file:
                                              names absent from the target first, then target order

compiles it with the pinned flags in tests/flags.json, and compares every
function symbol of tests/suites/<suite>/target.o against the result
(tests/lib/objcmp.py). Output: {"<suite>/<function>": {status, reason, stage, frac}}.

Stages: compile (the TU did not compile), missing (function not in the output
object), match (present, bytes or relocations differ). `frac` is the fraction of
matching instructions; PASS has frac 1.0.
"""

from __future__ import annotations

import argparse
import concurrent.futures as cf
import fnmatch
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "lib"))
import objcmp  # noqa: E402

FLAGS = json.loads((HERE / "flags.json").read_text())
STUB = "TODO(decomp)"


def tree_root() -> Path:
    return HERE.parent


def split_suite(suite: str) -> tuple[str, str]:
    proj, _, tu = suite.partition("-")
    return proj, tu


def is_stub(path: Path) -> bool:
    if not path.exists():
        return True
    t = path.read_text(errors="replace")
    return STUB in t or "{" not in t


def tu_source(root: Path, suite: str, order: list[str]) -> str:
    proj, tu = split_suite(suite)
    types = sorted((root / "src" / proj / "types").glob("*.h"))
    tud = root / "src" / proj / tu
    hdrs = sorted(tud.glob("*.h"))
    cfiles = [p for p in tud.glob("*.c") if not is_stub(p)]
    rank = {n: i for i, n in enumerate(order)}
    # files the target does not name (inlined helpers, data) first, alphabetically; then target order
    cfiles.sort(key=lambda p: (p.stem in rank, rank.get(p.stem, 0), p.stem))
    lines = [f"/* generated by tests/run.py for {suite} */"]
    lines += [f'#include "{p}"' for p in types + hdrs + cfiles]
    return "\n".join(lines) + "\n"


ASM = re.compile(r"\b(__asm__|__asm|asm)\b")
# Attributes and pragmas that steer gcc's inlining, cloning or emission are not reconstruction:
# `used` makes gcc emit a static function nobody calls yet, and blocks the .part/.isra clones
# the targets have (2026-10-13: 31 files carried them 17 minutes into the first launch).
STEER = re.compile(r"__attribute__\s*\(\([^)]*\b(used|noinline|noipa|noclone|optimize|flatten|always_inline|"
                   r"externally_visible|retain|section)\b|#\s*pragma\s+GCC")


def compile_tu(root: Path, suite: str, order: list[str], workdir: Path) -> tuple[Path | None, str]:
    proj, tu = split_suite(suite)
    src = workdir / f"{suite}.c"
    text = tu_source(root, suite, order)
    for inc in re.findall(r'#include "(.+)"', text):
        body = Path(inc).read_text(errors="replace")
        if ASM.search(body):
            return None, f"{inc}:1:1: error: inline assembly is not a reconstruction\n"
        m = STEER.search(body)
        if m:
            return None, (f"{inc}:1:1: error: '{m.group(1) or 'pragma GCC'}' steers gcc's inlining or emission; "
                          f"write the callers instead\n")
    src.write_text(text)
    obj = workdir / f"{suite}.o"
    pf = FLAGS.get("projects", {}).get(proj, {})
    cmd = [FLAGS["cc"], "-c", FLAGS["opt"], *FLAGS["common"], *FLAGS["diagnostics"], *pf.get("defines", []),
           f"-I{root / 'src' / proj / 'types'}", f"-I{root / 'src' / proj / tu}"]
    cmd += [f"-I{root / inc}" for inc in pf.get("include", [])]
    if os.environ.get("DECOMP_EXTRA_I"):        # validation only: the original headers, never in a worker tree
        cmd.append(f"-I{Path(os.environ['DECOMP_EXTRA_I']) / proj}")
    cmd += [str(src), "-o", str(obj)]
    p = subprocess.run(cmd, capture_output=True, text=True, errors="replace", timeout=300)
    if p.returncode != 0:
        return None, p.stderr
    return obj, p.stderr


def first_error(stderr: str) -> str:
    for line in stderr.splitlines():
        if "error:" in line:
            msg = line.split("error:", 1)[1].strip()
            return msg[:200]
    return (stderr.strip().splitlines() or ["compiler failed"])[-1][:200]


def error_files(stderr: str, root: Path) -> list[str]:
    out = []
    for m in re.finditer(r"^(/[^:\s]+):\d+:\d+: (?:fatal )?error:", stderr, re.M):
        p = m.group(1)
        try:
            out.append(str(Path(p).relative_to(root)))
        except ValueError:
            out.append(p)
    return list(dict.fromkeys(out))


def run_suite(root: Path, suite: str, filters: list[str], verbose: bool) -> tuple[dict, list[str]]:
    sd = HERE / "suites" / suite
    target = objcmp.Obj(str(sd / "target.o"))
    names = [n for n in target.order if not filters or any(fnmatch.fnmatchcase(f"{suite}/{n}", g) for g in filters)]
    res: dict = {}
    notes: list[str] = []
    if not names:
        return res, notes
    proj, tu = split_suite(suite)
    with tempfile.TemporaryDirectory(prefix="decomp-") as td:
        obj, stderr = compile_tu(root, suite, target.order, Path(td))
        if obj is None:
            msg = first_error(stderr)
            files = error_files(stderr, root)
            for n in names:
                res[f"{suite}/{n}"] = {"status": "FAIL", "stage": "compile", "frac": 0.0,
                                       "reason": f"compile: {msg}"}
            if verbose:
                notes.append(f"== {suite}: COMPILE ERROR in {', '.join(files) or '?'}\n{stderr[-3000:]}")
            return res, notes
        got = objcmp.Obj(str(obj))
        for n in names:
            tid = f"{suite}/{n}"
            base = re.sub(r"\.(part|isra|constprop|cold|lto_priv)(\.\d+)*$", "", n)
            base = re.sub(r"\.(part|isra|constprop)\.\d+.*$", "", base)
            if n not in got.funcs:
                f = root / "src" / proj / tu / f"{base}.c"
                if is_stub(f):
                    # bucket by size: up to three parallel clusters per TU, small functions first
                    sz = target.funcs[n].size
                    bucket = "small" if sz < 64 else "medium" if sz < 256 else "large"
                    r = {"status": "FAIL", "stage": "missing", "frac": 0.0,
                         "reason": f"stub: {bucket} function not yet written in {suite}"}
                elif base != n:
                    r = {"status": "FAIL", "stage": "missing", "frac": 0.0,
                         "reason": f"absent: gcc made no {n.split('.', 1)[1].split('.')[0]} clone in {suite}"}
                else:
                    r = {"status": "FAIL", "stage": "missing", "frac": 0.0,
                         "reason": f"absent: written but gcc emitted no code for it in {suite} "
                                   f"(a static function needs its callers written; or gcc inlined it)"}
                res[tid] = r
                if verbose:
                    have = sorted(got.funcs)
                    notes.append(f"== {tid}: {r['reason']}\n   functions your TU produced: {' '.join(have)[:600]}")
                continue
            r = objcmp.compare(target, got, n, suite)
            res[tid] = r
            if verbose:
                head = f"== {tid}: {r['status']}  {r['reason']}  frac={r['frac']}"
                if r["status"] != "PASS":
                    d = objcmp.diff_text(objcmp.body(target, n), objcmp.body(got, n))
                    head += "\n" + d
                notes.append(head)
    return res, notes


def list_suites() -> list[str]:
    return sorted(p.name for p in (HERE / "suites").iterdir() if (p / "target.o").exists())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite", default="", help="comma list; empty or 'all' = every suite")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 2)
    ap.add_argument("--json", default="")
    ap.add_argument("--filter", action="append", default=[])
    ap.add_argument("--baseline", default="", help="earlier --json output: print tests that no longer pass")
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args()
    root = tree_root()
    suites = list_suites() if a.suite in ("", "all") else [s for s in a.suite.split(",") if s]
    known = set(list_suites())
    bad = [s for s in suites if s not in known]
    if bad:
        print(f"unknown suite(s): {', '.join(bad)}", file=sys.stderr)
        suites = [s for s in suites if s in known]
    results: dict = {}
    notes: list[str] = []
    with cf.ThreadPoolExecutor(max_workers=max(1, a.jobs)) as ex:
        for res, nt in ex.map(lambda s: run_suite(root, s, a.filter, a.verbose), suites):
            results.update(res)
            notes += nt
    if a.json:
        Path(a.json).write_text(json.dumps(results, indent=0, sort_keys=True))
    if a.verbose:
        print("\n\n".join(notes))
    npass = sum(1 for r in results.values() if r["status"] == "PASS")
    if not a.quiet:
        print(f"{npass}/{len(results)} functions match")
    if a.baseline:
        old = json.loads(Path(a.baseline).read_text())
        lost = sorted(t for t, r in old.items() if r.get("status") == "PASS" and results.get(t, {}).get("status") != "PASS")
        print(f"REGRESSIONS vs baseline: {len(lost)}" + (": " + " ".join(lost[:30]) if lost else ""))
        return 1 if lost else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
