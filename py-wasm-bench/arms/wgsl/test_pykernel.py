"""Tests for pykernel: type inference, buffer access, rejections, one golden translation.

Run: python3 test_pykernel.py        (or: python3 -m pytest test_pykernel.py)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from pykernel import KernelError, kernel, translate, translate_source


def _ks(body, sig="gid: int, out: list[float], n: int"):
    return f"@kernel\ndef t({sig}):\n" + "".join(f"    {line}\n" for line in body.splitlines())


def _spec(body, sig="gid: int, out: list[float], n: int"):
    return translate_source(_ks(body, sig))


def _rejects(src, node, line=None):
    try:
        translate_source(src)
    except KernelError as e:
        assert node in str(e), f"expected {node!r} in: {e}"
        if line is not None:
            assert e.line == line, f"expected line {line}, got {e.line}: {e}"
        return str(e)
    raise AssertionError(f"accepted, expected rejection naming {node!r}:\n{src}")


# ---- golden translation -------------------------------------------------------

GOLDEN_SAXPY = """// generated by pykernel from saxpy(); do not edit

struct Params {
  pk_count: i32,
  a: f32,
}

@group(0) @binding(0) var<storage, read> x: array<f32>;
@group(0) @binding(1) var<storage, read_write> y: array<f32>;
@group(0) @binding(2) var<uniform> pk_params: Params;

@compute @workgroup_size(32)
fn main(@builtin(global_invocation_id) pk_gid: vec3<u32>) {
  let gid: i32 = i32(pk_gid.x);
  if (gid >= pk_params.pk_count) { return; }
  y[gid] = ((pk_params.a * x[gid]) + y[gid]);
}
"""


def test_golden_saxpy():
    spec = translate_source('''
@kernel(workgroup_size=32)
def saxpy(gid: int, x: list[float], y: list[float], a: float):
    y[gid] = a * x[gid] + y[gid]
''', name="saxpy")
    assert spec.wgsl == GOLDEN_SAXPY, spec.wgsl
    assert [(b.name, b.binding, b.access) for b in spec.buffers] == [("x", 0, "read"), ("y", 1, "read_write")]
    assert [(u.name, u.type, u.offset) for u in spec.uniforms] == [("pk_count", "i32", 0), ("a", "f32", 4)]
    assert spec.uniform_binding == 2 and spec.uniform_size == 8 and spec.workgroup_size == 32


def test_translate_from_function_object():
    @kernel
    def double(gid: int, v: list[float]):
        v[gid] = v[gid] * 2.0

    spec = translate(double)
    assert "fn main(" in spec.wgsl
    assert "v[gid] = (v[gid] * 2.0f);" in spec.wgsl
    assert spec.workgroup_size == 64


# ---- type inference -----------------------------------------------------------

def test_inference_int_float_bool():
    s = _spec("""k = 0
c = k < 3
q = k / 2
r = 0.5
m = min(k, 2)
f = sqrt(2)
t = k * 0.5
""")
    w = s.wgsl
    assert "var k: i32 = 0i;" in w
    assert "var c: bool = false;" in w
    assert "var q: f32 = 0.0f;" in w           # Python true division gives float
    assert "var r: f32 = 0.0f;" in w
    assert "var m: i32 = 0i;" in w             # min of ints stays int
    assert "var f: f32 = 0.0f;" in w           # sqrt is float
    assert "var t: f32 = 0.0f;" in w           # int * float is float
    assert "q = (f32(k) / f32(2i));" in w


def test_inference_widens_int_to_float_across_assignments():
    s = _spec("""x = 0
x = x + 0.5
""")
    assert "var x: f32 = 0.0f;" in s.wgsl
    assert "x = f32(0i);" in s.wgsl            # the int literal is converted where it lands
    assert "x = (x + 0.5f);" in s.wgsl


def test_inference_loop_carried_widening():
    # x is first read as int in the loop body and only later assigned a float: the
    # fixpoint must still settle on f32 and convert the earlier int assignment.
    s = _spec("""x = 0
for i in range(n):
    x = x + 1
    x = x * 0.5
""")
    assert "var x: f32 = 0.0f;" in s.wgsl


def test_annotated_local_sets_type():
    s = _spec("v: float = 3\nw: int = 2\n")
    assert "var v: f32 = 0.0f;" in s.wgsl and "v = f32(3i);" in s.wgsl
    assert "var w: i32 = 0i;" in s.wgsl


def test_int_division_and_floor_helpers():
    s = _spec("a = gid // n\nb = gid % n\n")
    assert "fn pk_floordiv(" in s.wgsl and "fn pk_mod(" in s.wgsl
    assert "a = pk_floordiv(gid, pk_params.n);" in s.wgsl
    s2 = _spec("a = gid + 1\n")
    assert "pk_mod" not in s2.wgsl and "pk_floordiv" not in s2.wgsl  # helpers only when used


def test_mixed_comparison_promotes():
    s = _spec("c = 2 < gid * 0.5\nif c:\n    out[gid] = 1.0\n")
    assert "(f32(2i) < " in s.wgsl


# ---- buffers and uniforms -----------------------------------------------------

def test_buffer_access_read_vs_read_write():
    s = translate_source(_ks("out[gid] = a[gid] + b[gid]", "gid: int, a: list[float], b: list[float], out: list[float]"))
    acc = {b.name: b.access for b in s.buffers}
    assert acc == {"a": "read", "b": "read", "out": "read_write"}, acc


def test_augmented_store_is_read_write():
    s = translate_source(_ks("v[gid] += 1.0", "gid: int, v: list[float]"))
    assert s.buffers[0].access == "read_write"
    assert "v[gid] = (v[gid] + 1.0f);" in s.wgsl


def test_uniform_fields_and_read_only_scalars():
    s = translate_source(_ks("out[gid] = x * float(n)", "gid: int, out: list[float], n: int, x: float"))
    assert [(u.name, u.type) for u in s.uniforms] == [("pk_count", "i32"), ("n", "i32"), ("x", "f32")]
    assert "out[gid] = (pk_params.x * f32(pk_params.n));" in s.wgsl
    _rejects(_ks("n = 3", "gid: int, out: list[float], n: int"), "read-only")


def test_reserved_wgsl_names_are_mangled():
    s = translate_source(_ks("select = 1.0\nout[gid] = select", "gid: int, out: list[float]"))
    assert "var pk_select: f32" in s.wgsl and "out[gid] = pk_select;" in s.wgsl


def test_for_loop_codegen_evaluates_bound_once_and_hoists_variable():
    s = _spec("for i in range(2, n):\n    out[gid] = float(i)\n")
    w = s.wgsl
    assert "let pk_end0: i32 = pk_params.n;" in w
    assert "for (var pk_it0: i32 = 2i; pk_it0 < pk_end0; pk_it0 = pk_it0 + 1i) {" in w
    assert "i = pk_it0;" in w and "var i: i32 = 0i;" in w


# ---- rejections -----------------------------------------------------------------

def test_reject_lambda_names_node_and_line():
    msg = _rejects('@kernel\ndef t(gid: int, out: list[float]):\n    f = lambda x: x\n', "Lambda", line=3)
    assert "line 3" in msg


def test_reject_list_literal_and_comprehension():
    _rejects(_ks("y = [1, 2]"), "List")
    _rejects(_ks("y = [i for i in range(3)]"), "ListComp")


def test_reject_call_to_unknown_function_and_attribute_call():
    _rejects(_ks("print(gid)"), "print")
    _rejects(_ks("y = math.sqrt(2.0)"), "Attribute")


def test_reject_string_and_tuple_and_multi_assign():
    _rejects(_ks("s = 'hi'"), "string")
    _rejects(_ks("a, b = 1, 2"), "Tuple")
    _rejects(_ks("a = b = 1"), "chained")


def test_reject_power_bitwise_chained_compare_ifexp():
    _rejects(_ks("y = 2 ** 3"), "Pow")
    _rejects(_ks("y = 3 & 1"), "BitAnd")
    _rejects(_ks("y = 1 < gid < 3"), "chained")
    _rejects(_ks("y = 1 if gid else 2"), "IfExp")


def test_reject_while_else_for_else_and_for_over_non_range():
    _rejects(_ks("while gid < 2:\n    break\nelse:\n    pass"), "While")
    _rejects(_ks("for i in range(3):\n    pass\nelse:\n    pass"), "For")
    _rejects(_ks("for v in out:\n    pass"), "range")
    _rejects(_ks("for i in range(0, 10, 2):\n    pass"), "range")


def test_reject_truthiness_of_number_and_float_index():
    _rejects(_ks("if gid:\n    pass"), "condition")
    _rejects(_ks("out[0.5] = 1.0"), "int")


def test_reject_float_floor_div_and_mod():
    _rejects(_ks("y = 1.5 % 2.0"), "int operands")


def test_reject_unannotated_or_unsupported_parameter_types():
    _rejects("@kernel\ndef t(gid: int, xs: list[int]):\n    pass\n", "list[int]")
    _rejects("@kernel\ndef t(gid: int, d: dict):\n    pass\n", "dict")
    _rejects("@kernel\ndef t(gid: int, x):\n    pass\n", "x")
    _rejects("@kernel\ndef t(i: float, out: list[float]):\n    pass\n", "int")


def test_reject_nested_lists_and_non_list_indexing():
    _rejects(_ks("y = n[gid]", "gid: int, out: list[float], n: int"), "indexed")
    _rejects(_ks("out[gid] = 1.0", "gid: int, out: list[float]").replace("out[gid]", "out[gid][0]"), "assigned by index")


def test_reject_return_value_and_stray_break():
    _rejects(_ks("return 1"), "return")
    _rejects(_ks("break"), "break")


def test_reject_use_before_assignment():
    _rejects(_ks("y = z + 1\nz = 2"), "'z'")
    _rejects(_ks("if gid > 1:\n    z = 2\ny = z"), "'z'")      # assigned in one branch only
    _rejects(_ks("for i in range(n):\n    z = i\ny = z"), "'z'")  # loop body may not run
    _rejects(_ks("y = q"), "'q'")                             # never assigned at all


def test_int_variable_widens_to_float_on_float_assignment():
    s = _spec("k = 0\nk = 1.5\n")
    assert "var k: f32 = 0.0f;" in s.wgsl and "k = 1.5f;" in s.wgsl


def test_reject_bool_arithmetic_and_bool_to_int_rebinding():
    _rejects(_ks("b = gid < 3\ny = b + 1"), "bool")
    _rejects(_ks("k = 0\nk = gid < 3"), "bool")


def test_reject_reserved_pk_names_and_missing_kernel_decorator():
    _rejects(_ks("pk_x = 1"), "pk_")
    try:
        translate_source("def t(gid: int):\n    pass\n")
    except KernelError as e:
        assert "@kernel" in str(e)
    else:
        raise AssertionError("missing @kernel accepted")


def test_error_line_numbers_are_file_relative():
    src = "@kernel\ndef t(gid: int, out: list[float]):\n    out[gid] = 1.0\n    f = lambda: 0\n"
    try:
        translate_source(src, first_line=40)
    except KernelError as e:
        assert e.line == 43, e.line
    else:
        raise AssertionError("lambda accepted")


# ---- math builtins ------------------------------------------------------------

def test_float_math_builtins_coerce_ints_and_return_f32():
    s = _spec("x = sin(gid) + cos(1.0) + exp(0.5) + log(2.0) + tan(0.1)\n"
              "y = atan2(gid, n) + pow(2.0, 3)\nout[gid] = x + y")
    w = s.wgsl
    assert "var x: f32" in w and "var y: f32" in w
    assert "sin(f32(gid))" in w and "atan2(f32(gid), f32(pk_params.n))" in w
    assert "pow(2.0f, 3.0f)" in w or "pow(2.0f, f32(3i))" in w


def test_floor_returns_int_like_math_floor():
    s = _spec("k = floor(2.5 * float(gid))\nout[gid] = float(k)")
    assert "var k: i32" in s.wgsl and "i32(floor(" in s.wgsl


def test_abs_keeps_its_argument_type():
    s = _spec("a = abs(gid - n)\nb = abs(-0.5)\nout[gid] = float(a) + b")
    assert "var a: i32" in s.wgsl and "var b: f32" in s.wgsl


def test_math_builtin_arity_and_unknown_names():
    _rejects(_ks("out[gid] = atan2(1.0)"), "atan2() takes 2")
    _rejects(_ks("out[gid] = hypot(1.0, 2.0)"), "hypot")


def test_math_builtins_run_as_python():
    """The kernel source stays plain Python: importing math makes it executable."""
    from math import atan2, cos, exp, floor, log, sin
    out = [0.0] * 4
    def k(gid, out, n):
        out[gid] = sin(gid) + cos(1.0) + exp(0.5) + log(2.0) + atan2(gid, n) + float(floor(1.5))
    for g in range(4):
        k(g, out, 4)
    assert abs(out[1] - (0.8414709848 + 0.5403023059 + 1.6487212707 + 0.6931471806
                         + 0.2449786631 + 1.0)) < 1e-9

