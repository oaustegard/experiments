// Builds bridge/speed_job.js (+ spec) : per-pixel vs instanced frame times for the given splat lists.
import fs from "fs";
import { emitWGSL } from "../web/trainer.js";
import { emitInstanced, createRenderer } from "../web/instanced.js";
const inp = JSON.parse(fs.readFileSync("scratch/speed_in.json"));
const spec = Object.entries(inp).map(([id, j]) => { const r = { P: Int32Array.from(j.P), bg: Int32Array.from(j.bg), A: j.A, n: j.n };
  return { id, n: j.n, perPixel: emitWGSL(r), instanced: emitInstanced(r) }; });
fs.writeFileSync("bridge/speed_spec.json", JSON.stringify({ sizes: [[768, 512], [1920, 1280], [3840, 2560]], reps: 5, shaders: spec }));
fs.writeFileSync("bridge/speed_job.js", `// GPU Bridge job: frame time of the per-pixel shader vs the instanced renderer (generated by scratch/make_speed_job.mjs).
// Input spec (u8 JSON): {sizes, reps, shaders: [{id, n, perPixel, instanced}]}. Frames over 2 s end that renderer's timing.
const spec = JSON.parse(new TextDecoder().decode(ctx.inputs.spec));
const ad = await navigator.gpu.requestAdapter();
const dev = await ad.requestDevice({ requiredFeatures: ad.features.has("float32-blendable") ? ["float32-blendable"] : [] });
${createRenderer.toString()}
const ub = dev.createBuffer({ size: 16, usage: GPUBufferUsage.UNIFORM | GPUBufferUsage.COPY_DST });
function perPixel(code) {
  const mod = dev.createShaderModule({ code });
  const pipe = dev.createRenderPipeline({ layout: "auto", vertex: { module: mod, entryPoint: "vs" }, fragment: { module: mod, entryPoint: "fs", targets: [{ format: "rgba8unorm" }] } });
  const bg = dev.createBindGroup({ layout: pipe.getBindGroupLayout(0), entries: [{ binding: 0, resource: { buffer: ub } }] });
  return { draw(view, w, h) { dev.queue.writeBuffer(ub, 0, new Float32Array([w, h, 0, 0])); const e = dev.createCommandEncoder();
    const p = e.beginRenderPass({ colorAttachments: [{ view, loadOp: "clear", storeOp: "store", clearValue: [1, 1, 1, 1] }] });
    p.setPipeline(pipe); p.setBindGroup(0, bg); p.draw(3); p.end(); dev.queue.submit([e.finish()]); } };
}
const rows = []; let k = 0, total = spec.shaders.length * spec.sizes.length * 2;
for (const s of spec.shaders) {
  const R = { perPixel: perPixel(s.perPixel), instanced: createRenderer(dev, "rgba8unorm", s.instanced) };
  for (const [name, r] of Object.entries(R)) {
    let slow = false;
    for (const [w, h] of spec.sizes) {
      if (slow) { rows.push({ id: s.id, renderer: name, size: w + "x" + h, skipped: true }); ctx.progress(++k / total); continue; }
      const tex = dev.createTexture({ size: [w, h], format: "rgba8unorm", usage: GPUTextureUsage.RENDER_ATTACHMENT });
      const t = [];
      for (let i = 0; i <= spec.reps; i++) { const t0 = performance.now(); r.draw(tex.createView(), w, h, s.n); await dev.queue.onSubmittedWorkDone();
        const ms = performance.now() - t0; if (i > 0) t.push(ms); if (ms > 2000) { slow = true; t.push(ms); break; } }
      tex.destroy(); t.sort((a, b) => a - b);
      rows.push({ id: s.id, n: s.n, renderer: name, size: w + "x" + h, medianMs: t[Math.floor(t.length / 2)], minMs: t[0] });
      ctx.log(JSON.stringify(rows.at(-1))); ctx.progress(++k / total, s.id + " " + name + " " + w + "x" + h);
    }
  }
}
return { rows, float32Blendable: dev.features.has("float32-blendable") };
`);
console.log("ok", spec.map((s) => [s.id, s.perPixel.length, s.instanced.length]));
